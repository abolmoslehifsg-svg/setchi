export function getOutfitById(id: string): Outfit | undefined {
  return outfits.find((o) => o.id === id);
}

export function getOutfitsByStyle(style: string): Outfit[] {
  return outfits.filter((o) => o.style.includes(style as never));
}

export function getOutfitsByOccasion(occasion: string): Outfit[] {
  return outfits.filter((o) => o.occasion.includes(occasion as never));
}
